/// Guides the user through setting up two factor authentication. It
/// presents instructions for using an authenticator app and enables
/// two factor via the profile cubit upon completion. This is a
/// simplified mock implementation for demonstration.
class TwoFactorSetupPage extends StatelessWidget {
  const TwoFactorSetupPage({Key? key}) : super(key: key);

  @override
  Widget build(BuildContext context) {
    return BlocProvider<ProfileCubit>(
      create: (_) => getIt<ProfileCubit>(),
      child: BlocConsumer<ProfileCubit, ProfileState>(
        listener: (context, state) async {
          if (state.status == Status.error && state.message != null) {
            ScaffoldMessenger.of(context).showSnackBar(
              SnackBar(content: Text(state.message!)),
            );
          }
          if (state.status == Status.success) {
            await showSuccessDialog(context,
                title: 'Two Factor Enabled',
                message:
                    'You have successfully enabled two factor authentication');
            Navigator.of(context).pop();
          }
        },
        builder: (context, state) {
          if (state.status == Status.loading) {
            return const LoadingWidget();
          }
          return AppScaffold(
            appBar: AppBar(title: const Text('Two Factor Setup')),
            body: SingleChildScrollView(
              child: Padding(
                padding: const EdgeInsets.all(AppSpacing.lg),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text('Authenticator App', style: AppTypography.h3),
                    const SizedBox(height: AppSpacing.sm),
                    AppCard(
                      child: Column(
                        crossAxisAlignment: CrossAxisAlignment.start,
                        children: [
                          Text('Step 1', style: AppTypography.subtitle1),
                          const SizedBox(height: AppSpacing.xs),
                          Text(
                              'Download an authenticator app such as Google Authenticator or Authy.',
                              style: AppTypography.body2),
                          const SizedBox(height: AppSpacing.md),
                          Text('Step 2', style: AppTypography.subtitle1),
                          const SizedBox(height: AppSpacing.xs),
                          Text(
                              'Scan the QR code below with your authenticator app.',
                              style: AppTypography.body2),
                          const SizedBox(height: AppSpacing.md),
                          Center(
                            child: Container(
                              height: 150,
                              width: 150,
                              decoration: BoxDecoration(
                                color: AppColorsDS.surface,
                                borderRadius: BorderRadius.circular(8),
                              ),
                              child: const Icon(Icons.qr_code_2,
                                  size: 64, color: AppColorsDS.primary),
                            ),
                          ),
                          const SizedBox(height: AppSpacing.md),
                          Text('Step 3', style: AppTypography.subtitle1),
                          const SizedBox(height: AppSpacing.xs),
                          Text(
                              'Enter the 6-digit code generated by your app to verify.',
                              style: AppTypography.body2),
                          const SizedBox(height: AppSpacing.md),
                          Text('Backup Codes', style: AppTypography.subtitle1),
                          const SizedBox(height: AppSpacing.xs),
                          Text(
                              'Write down these backup codes and store them securely. Each code can only be used once.',
                              style: AppTypography.body2),
                          const SizedBox(height: AppSpacing.md),
                          Wrap(
                            spacing: AppSpacing.sm,
                            children: const [
                              AppChip(label: '1234-ABCD'),
                              AppChip(label: '5678-EFGH'),
                              AppChip(label: '9012-IJKL'),
                              AppChip(label: '3456-MNOP'),
                              AppChip(label: '7890-QRST'),
                            ],
                          ),
                          const SizedBox(height: AppSpacing.lg),
                          Center(
                            child: PrimaryButton(
                              label: 'Enable Two Factor',
                              onPressed: () {
                                context
                                    .read<ProfileCubit>()
                                    .toggleTwoFactor(true);
                              },
                            ),
                          ),
                        ],
                      ),
                    ),
                    const SectionSpacing(),
                    Text('SMS (Mock)', style: AppTypography.h3),
                    const SizedBox(height: AppSpacing.sm),
                    AppCard(
                      child: Column(
                        crossAxisAlignment: CrossAxisAlignment.start,
                        children: [
                          Text(
                              'We will send a verification code via SMS to your registered phone number.',
                              style: AppTypography.body2),
                          const SizedBox(height: AppSpacing.md),
                          PrimaryButton(
                            label: 'Enable via SMS',
                            onPressed: () {
                              // For mock, simply enable two factor and return
                              context
                                  .read<ProfileCubit>()
                                  .toggleTwoFactor(true);
                            },
                          ),
                        ],
                      ),
                    ),
                  ],
                ),
              ),
            ),
          );
        },
      ),
    );
  }
}
